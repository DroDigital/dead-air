const ALIAS: Record<string, string> = { '—': '-', '–': '-', '−': '-', '’': "'", '‘': "'", '“': '"', '”': '"', é: 'E', É: 'E' };

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;
export const LINE_H = 9;

/** True if the bitmap font can draw this character (after aliasing and upper-casing). */
export function supportsGlyph(ch: string): boolean {
  const c = ALIAS[ch] ?? ch.toUpperCase();
  return Object.prototype.hasOwnProperty.call(G, c);
}

function glyph(ch: string): number[] {
  const c = ALIAS[ch] ?? ch.toUpperCase();
  return G[c] ?? G['?'];
}

export function textWidth(s: string, scale = 1): number {
  return s.length ? (s.length * ADVANCE - 1) * scale : 0;
}

export interface DrawOpts {
  scale?: number;
  color?: string;
  shadow?: string | null;
  align?: 'left' | 'center' | 'right';
}

/** Draw text pixel-by-pixel (no anti-aliasing). Returns the drawn width. */
export function drawText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, o: DrawOpts = {}): number {
  const k = Math.max(1, Math.round(o.scale ?? 1));
  const w = textWidth(s, k);
  let x0 = Math.round(x);
  if (o.align === 'center') x0 = Math.round(x - w / 2);
  else if (o.align === 'right') x0 = Math.round(x - w);
  const y0 = Math.round(y);
  const pass = (col: string, dx: number, dy: number) => {
    ctx.fillStyle = col;
    for (let i = 0; i < s.length; i++) {
      const g = glyph(s[i]);
      const gx = x0 + i * ADVANCE * k + dx;
      for (let r = 0; r < GLYPH_H; r++) {
        const row = g[r];
        if (!row) continue;
        for (let c = 0; c < GLYPH_W; c++) if (row & (1 << (GLYPH_W - 1 - c))) ctx.fillRect(gx + c * k, y0 + r * k + dy, k, k);
      }
    }
  };
  if (o.shadow) pass(o.shadow, k, k);
  pass(o.color ?? '#fff', 0, 0);
  return w;
}

/** Greedy word wrap into lines of at most `maxChars`. */
export function wrapText(s: string, maxChars: number): string[] {
  const out: string[] = [];
  for (const para of s.split('\n')) {
    let line = '';
    for (const word of para.split(/\s+/)) {
      if (!word) continue;
      if (!line) line = word;
      else if (line.length + 1 + word.length <= maxChars) line += ' ' + word;
      else {
        out.push(line);
        line = word;
      }
      while (line.length > maxChars) {
        out.push(line.slice(0, maxChars));
        line = line.slice(maxChars);
      }
    }
    out.push(line);
  }
  return out;
}
